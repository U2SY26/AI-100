def analyze_regions():
    """모든 메뉴명에서 지역명 찾기"""

    # 검색할 지역명 목록 (확장)
    regions = {
        "안동": [],
        "전주": [],
        "베트남": [],
        "나가사키": [],
        "태국": [],
        "춘천": [],
        "제주": [],
        "부산": [],
        "일본": [],
        "중국": [],
        "이탈리아": [],
        "프랑스": [],
        "인도": [],
        "멕시코": [],
        "스페인": [],
    }

    all_menus = menu_list_january + menu_list_february

    print("=" * 60)
    print("문제 3번: 지역 특색 메뉴 검증")
    print("=" * 60)
    print(f"\n총 메뉴 개수: {len(all_menus)}개")
    print("검색 대상 지역: ", ", ".join(regions.keys()))

    # 각 메뉴명에서 지역명 검색
    for menu in all_menus:
        for region in regions.keys():
            if region in menu:
                regions[region].append(menu)

    # 결과 출력
    print("\n" + "=" * 60)
    print("지역명 검색 결과")
    print("=" * 60)

    found_regions = {}
    for region, menus in sorted(regions.items()):
        count = len(menus)
        if count > 0:
            found_regions[region] = count
            print(f"\n{region}: {count}회")
            for menu in menus:
                print(f"  - {menu}")

    # 2회 이상 등장한 지역
    print("\n" + "=" * 60)
    print("2회 이상 등장한 지역 (답안)")
    print("=" * 60)

    result = [region for region, count in found_regions.items() if count >= 2]

    if result:
        print("\n✅ 답:", ", ".join(sorted(result)))
        print(f"\n총 {len(result)}개 지역")
    else:
        print("\n❌ 2회 이상 등장한 지역이 없습니다.")

    return result


